// Helper to filter blueprints by education system, programme, and class
export function filterBlueprints(
  blueprints: BoardQuestionBlueprint[],
  systemId?: CurriculumSystemId | 'ALL',
  programme?: string,
  targetClass?: string
): BoardQuestionBlueprint[] {
  return blueprints.filter((b) => {
    if (systemId && systemId !== 'ALL') {
      const bSys = b.systemId || (b.board === 'ICSE' || b.board === 'CISCE' || b.board === 'ISC' ? 'CISCE' : b.board.startsWith('Cambridge') ? 'Cambridge' : b.board);
      if (bSys !== systemId) return false;
    }
    if (programme && programme !== 'ALL') {
      if (b.programme && b.programme !== programme) return false;
    }
    if (targetClass && targetClass !== 'ALL') {
      if (b.targetClass !== targetClass) return false;
    }
    return true;
  });
}

